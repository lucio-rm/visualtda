#!/usr/bin/env node
/**
 * Visual TDA - Canonical Solution Pre-build Encryptor
 * 
 * Encrypts all canonical Python solutions in exercises/ into AES-256-GCM ciphertexts
 * with PBKDF2 key derivations for Instructor Mode and Student Pass tokens.
 * Produces src/engine/encryptedSolutions.ts.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const exercisesDir = path.resolve(rootDir, 'exercises');
const outputFile = path.resolve(rootDir, 'src', 'engine', 'encryptedSolutions.ts');

const INSTRUCTOR_PASSWORD = 'MEL75.29';
const INSTRUCTOR_KDF_SALT = 'visual-tda-faculty-kdf-salt-75.29-2026';
const STUDENT_TOKEN_SALT = 'visual-tda-student-token-salt-75.29-2026';
const STUDENT_PASS_SECRET = 'visual-tda-pedagogical-test-pass-secret-2026';

const subtle = crypto.subtle;
const encoder = new TextEncoder();

function bufferToBase64(buffer) {
  return Buffer.from(buffer).toString('base64');
}

async function deriveInstructorKey(password) {
  const baseKey = await subtle.importKey(
    'raw',
    encoder.encode(password),
    { name: 'PBKDF2' },
    false,
    ['deriveKey']
  );

  return subtle.deriveKey(
    {
      name: 'PBKDF2',
      salt: encoder.encode(INSTRUCTOR_KDF_SALT),
      iterations: 100000,
      hash: 'SHA-256'
    },
    baseKey,
    { name: 'AES-GCM', length: 256 },
    false,
    ['encrypt', 'decrypt']
  );
}

async function deriveStudentKey(exerciseId) {
  const token = `${exerciseId}:${STUDENT_PASS_SECRET}`;
  const baseKey = await subtle.importKey(
    'raw',
    encoder.encode(token),
    { name: 'PBKDF2' },
    false,
    ['deriveKey']
  );

  return subtle.deriveKey(
    {
      name: 'PBKDF2',
      salt: encoder.encode(`${STUDENT_TOKEN_SALT}:${exerciseId}`),
      iterations: 10000,
      hash: 'SHA-256'
    },
    baseKey,
    { name: 'AES-GCM', length: 256 },
    false,
    ['encrypt', 'decrypt']
  );
}

async function encryptExercise(exerciseId, pythonCode, instructorKey) {
  // 1. Generate unique 256-bit AES-GCM payload key
  const payloadKey = await subtle.generateKey(
    { name: 'AES-GCM', length: 256 },
    true,
    ['encrypt', 'decrypt']
  );
  const rawPayloadKey = await subtle.exportKey('raw', payloadKey);

  // 2. Encrypt pythonCode
  const payloadIv = crypto.getRandomValues(new Uint8Array(12));
  const payloadCiphertext = await subtle.encrypt(
    { name: 'AES-GCM', iv: payloadIv },
    payloadKey,
    encoder.encode(pythonCode)
  );

  // 3. Wrap payload key with Instructor Key (Slot 1)
  const instructorWrapIv = crypto.getRandomValues(new Uint8Array(12));
  const instructorWrapCiphertext = await subtle.encrypt(
    { name: 'AES-GCM', iv: instructorWrapIv },
    instructorKey,
    rawPayloadKey
  );

  // 4. Wrap payload key with Student Pass Key (Slot 2)
  const studentKey = await deriveStudentKey(exerciseId);
  const studentWrapIv = crypto.getRandomValues(new Uint8Array(12));
  const studentWrapCiphertext = await subtle.encrypt(
    { name: 'AES-GCM', iv: studentWrapIv },
    studentKey,
    rawPayloadKey
  );

  return {
    exerciseId,
    iv: bufferToBase64(payloadIv),
    ciphertext: bufferToBase64(payloadCiphertext),
    keys: {
      instructor: {
        iv: bufferToBase64(instructorWrapIv),
        ciphertext: bufferToBase64(instructorWrapCiphertext)
      },
      student: {
        iv: bufferToBase64(studentWrapIv),
        ciphertext: bufferToBase64(studentWrapCiphertext)
      }
    }
  };
}

async function main() {
  console.log('🔒 Encrypting canonical Python solutions with AES-256-GCM + PBKDF2...');
  const instructorKey = await deriveInstructorKey(INSTRUCTOR_PASSWORD);

  const entries = fs.readdirSync(exercisesDir, { withFileTypes: true });
  const results = {};

  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const exerciseId = entry.name;
    const solutionPath = path.join(exercisesDir, exerciseId, 'solution.py');
    if (!fs.existsSync(solutionPath)) {
      console.warn(`⚠️ Warning: No solution.py found in ${exerciseId}`);
      continue;
    }

    const code = fs.readFileSync(solutionPath, 'utf-8');
    const encrypted = await encryptExercise(exerciseId, code, instructorKey);
    results[exerciseId] = encrypted;
  }

  // Handle alias for linear-programming-formulation
  if (results['linear-programming']) {
    const code = fs.readFileSync(path.join(exercisesDir, 'linear-programming', 'solution.py'), 'utf-8');
    results['linear-programming-formulation'] = await encryptExercise('linear-programming-formulation', code, instructorKey);
  }

  const generatedTs = `// AUTO-GENERATED BY scripts/encryptSolutions.mjs - DO NOT EDIT MANUALLY
// All canonical Python solutions are encrypted with AES-256-GCM.
// Zero plaintext algorithm code is present in this bundle.

import type { EncryptedSolutionPayload } from '../utils/solutionCrypto';

export const ENCRYPTED_SOLUTIONS: Record<string, EncryptedSolutionPayload> = ${JSON.stringify(results, null, 2)};
`;

  fs.writeFileSync(outputFile, generatedTs, 'utf-8');
  console.log(`✅ Successfully encrypted ${Object.keys(results).length} solutions to ${path.relative(rootDir, outputFile)}`);
}

main().catch((err) => {
  console.error('Fatal encryption error:', err);
  process.exit(1);
});
